# ----------------------------------------------------------------------------- ML section
def ml_tables(d):
    M = d["ml"]
    rr = [{"model": k, "RMSE (min)": f(v["rmse_min"], 3), "MAE (min)": f(v["mae_min"], 3), "R2": f(v["r2"], 3)} for k, v in M["regression"].items()]
    cr = [{"model": k, "accuracy": f(v["accuracy"], 3), "precision": f(v["precision"], 3), "recall": f(v["recall"], 3),
           "F1": f(v["f1"], 3), "AUC": f(v["auc"], 3) if v["auc"] is not None else "n/a"} for k, v in M["classification"].items()]
    return md_table(pd.DataFrame(rr)), md_table(pd.DataFrame(cr))


def ml_reading(d):
    """Plain, data-driven reading of the ML results (no claim the numbers do not support)."""
    M = d["ml"]
    r, c = M["regression"], M["classification"]
    g, ng, bm, bc = r["GBT (full features)"], r["GBT without previous delay"], r["baseline: train mean"], r["baseline: previous delay carried forward"]
    best_mae = min(bm["mae_min"], bc["mae_min"])
    gain = 100 * (best_mae - g["mae_min"]) / best_mae
    gain_ng = 100 * (bm["mae_min"] - ng["mae_min"]) / bm["mae_min"]
    cg, cng, cc = c["GBT (full features)"], c["GBT without previous delay"], c["baseline: previous delay carried forward"]
    tail = ("The model is only a small improvement over the best simple baseline." if gain < 5 else
            "The model is clearly better than the best simple baseline.")
    return (f"- **Regression.** On held-out days the full GBT has MAE {f(g['mae_min'],2)} min and R2 {f(g['r2'],2)}, against MAE {f(bm['mae_min'],2)} min for predicting the training mean "
            f"and {f(bc['mae_min'],2)} min for carrying the previous delay forward ({f(gain,1)}% lower MAE than the better baseline). {tail}\n"
            f"- **Where the skill comes from.** Without the previous-timepoint delay the GBT's MAE is {f(ng['mae_min'],2)} min ({f(gain_ng,1)}% below the mean baseline), "
            f"so schedule-only information (hour, weekday, route, timepoint) explains {'little' if gain_ng < 5 else 'some'} of the delay; the previous delay adds the rest.\n"
            f"- **Classification (late = more than {M['late_threshold_sec']//60} min).** Full GBT: accuracy {f(100*cg['accuracy'],1)}%, precision {f(100*cg['precision'],1)}%, recall {f(100*cg['recall'],1)}%, "
            f"F1 {f(cg['f1'],3)}, AUC {f(cg['auc'],3)}. Late rate in the test days is {f(100*M['split']['test']['late_rate'],1)}%, so accuracy alone is not informative; "
            f"the carried-forward baseline reaches AUC {f(cc['auc'],3)} and without the previous delay the GBT reaches AUC {f(cng['auc'],3)}.")


def ml_section(d, n="5"):
    M = d["ml"]
    if not M:
        return f"\n## {n}. Delay prediction\n\n{NM} (run `python -m src.delay_model`).\n"
    rt, ct = ml_tables(d)
    sp = M["split"]
    imp = d["ml_imp"]
    top = {}
    for task in ("regression", "classification"):
        t = imp[(imp.model == "GBT (full features)") & (imp.task == task)].sort_values("importance", ascending=False).head(4)
        top[task] = ", ".join(f"{r.feature} ({r.importance:.2f})" for r in t.itertuples())
    fits = M["fits"]
    return f"""
## {n}. Delay prediction (Spark MLlib)
**Task.** At the moment a bus leaves its previous timepoint, predict its delay at the next one: (a) delay in minutes (regression) and (b) late = more than {M['late_threshold_sec']//60} min (classification).
Only 'Schedule'-standard trips are used.

**Split (temporal, no leakage).** In each month the last {M['test_fraction']:.0%} of the days are held out. Train: {i(sp['train']['rows'])} events on {sp['train']['days']} days ({sp['train']['first_date']} to {sp['train']['last_date']}); the models are fitted on a
seeded sample of {i(M['train_rows_used'])} of them (cap {i(M['train_cap'])}, so local-mode training stays in minutes). Test: **{i(M['test_rows'])}** events on {sp['test']['days']} days. All metrics below are on the test days only.

**Features** (all known before the event): {', '.join(M['features_full'])}. `route_hist_*` and `rtp_hist_*` are route and route+timepoint averages computed on the training days only and broadcast-joined;
`prev_delay_min` is the delay at the previous timepoint of the same trip (a `lag` window over earlier stops only). Model: gradient-boosted trees (`GBTRegressor`, `GBTClassifier`), {M['gbt']['gbt_max_iter']} rounds, depth {M['gbt']['gbt_max_depth']}, seed {M['gbt']['seed']}.
The second model leaves out the previous-delay features to show how much they matter.

### Regression: delay in minutes
{rt}

### Classification: late or not
{ct}

{ml_reading(d)}

**Most used features** (full GBT): regression: {top['regression']}; classification: {top['classification']}. Importance shows what the trees split on, not what causes delay.

Fit times on {'4' if M else NM} cores: regressor {f(fits['reg_full']['fit_seconds'],1)} s, classifier {f(fits['clf_full']['fit_seconds'],1)} s (data preparation {f(M['prepare_seconds'],1)} s). Figures: `fig5_ml_regression.png`, `fig6_ml_classification.png`, `fig7_ml_feature_importance.png`.

**Reading this honestly.** The predictions are 'next-timepoint' forecasts, made when the bus leaves the previous timepoint, not day-ahead forecasts. The model is evaluated on later days of the same four months; it says nothing about other months, years or other cities.
"""


def bench_md(d):
    B = d["bench"]
    if not B:
        return NM
    rows = []
    for n, e in sorted(B["scaling"].items(), key=lambda kv: int(kv[0])):
        s = e["stages_seconds"]
        rows.append({"cores": n, "clean s": f(s['clean']['median'], 1), "window+agg s": f(s['window_agg']['median'], 1),
                     "total median s": f(s['total']['median'], 1), "min-max s": f"{f(s['total']['min'], 1)} - {f(s['total']['max'], 1)}",
                     "throughput rows/s": i(e['throughput_rows_per_s']), "speedup S_N": f(e['speedup_total']),
                     "efficiency": f(e['efficiency_total']), "oversubscribed": e['oversubscribed']})
    out = [md_table(pd.DataFrame(rows))]
    out.append(f"\n{i(B['cleaned_event_rows'])} cleaned events; {B['config']['timed_runs']} timed runs after {B['config']['warmup_runs']} discarded warm-up per core count; "
               f"{B['config']['driver_memory']} driver heap. Per-stage speedup: " + "; ".join(
                   f"{n} cores: " + ", ".join(f"{k} {f(v)}" for k, v in e['speedup_by_stage'].items())
                   for n, e in sorted(B['scaling'].items(), key=lambda kv: int(kv[0]))) + ".")
    ms = B.get("model_scaling")
    if ms:
        mr = []
        for n, e in sorted(ms["scaling"].items(), key=lambda kv: int(kv[0])):
            s = e["stages_seconds"]
            mr.append({"cores": n, "features s": f(s['features']['median'], 1), "fit regressor s": f(s['fit_regressor']['median'], 1),
                       "fit classifier s": f(s['fit_classifier']['median'], 1), "total median s": f(s['total']['median'], 1),
                       "speedup S_N": f(e['speedup_total']), "efficiency": f(e['efficiency_total'])})
        out.append(f"\n### Model training (features + GBT regressor + GBT classifier)\n\n" + md_table(pd.DataFrame(mr)) +
                   f"\n\n{i(ms['train_rows_used'])} training rows, {ms['gbt']['gbt_max_iter']} rounds, depth {ms['gbt']['gbt_max_depth']}; {ms['timed_runs']} timed run(s) after {ms['warmup_runs']} discarded warm-up.")
    jc = B.get("join_comparison")
    if jc:
        jr = [{"join variant": v, "median s": f(r['join_seconds']['median'], 3),
               "min-max s": f"{f(r['join_seconds']['min'], 3)} - {f(r['join_seconds']['max'], 3)}",
               "shuffle write bytes (median/run)": i(r['shuffle_write_bytes_per_run_median']) if not isinstance(r['shuffle_write_bytes_per_run_median'], str) else NM,
               "plan file": r['plan_file']} for v, r in jc["variants"].items()]
        out.append(f"\n### Broadcast vs shuffle join (local[{jc['cores']}])\n\n" + md_table(pd.DataFrame(jr)) +
                   f"\n\n{jc['what'].capitalize()}. Broadcast = `F.broadcast()` hint on the small history tables. Shuffle = no hint and "
                   "`spark.sql.autoBroadcastJoinThreshold=-1`, giving sort-merge joins with `Exchange` nodes (see the saved plans). Adaptive query execution is off "
                   "so Spark cannot silently switch strategy. Shuffle bytes come from the Spark event log; broadcast data movement is not counted as shuffle.")
    return "\n".join(out)


